def rep_once(text, old, new, name):
    c = text.count(old)
    check(name + " anchor x1", c == 1, "found=%d" % c)
    if c != 1:
        return text
    return text.replace(old, new, 1)


def rep_all(text, old, new, name, expect=None):
    c = text.count(old)
