// Cookie exporter for Python downloader
chrome.runtime.onMessage.addListener(function(msg, sender, sendResponse){
  if(msg && msg.type === 'GET_TIKTOK_COOKIES'){
    chrome.cookies.getAll({domain: 'tiktok.com'}, function(cookies){
      if(chrome.runtime.lastError || !cookies){
        sendResponse({success: false, error: (chrome.runtime.lastError && chrome.runtime.lastError.message) || 'No cookies'});
        return;
      }
      var lines = ['# Netscape HTTP Cookie File', '# Generated by Custom TikTok Downloader', ''];
      for(var i = 0; i < cookies.length; i++){
        var c = cookies[i];
        var d = c.domain || '.tiktok.com';
        if(!d.startsWith('.')) d = '.' + d;
        var flag = d.startsWith('.') ? 'TRUE' : 'FALSE';
        var p = c.path || '/';
        var s = c.secure ? 'TRUE' : 'FALSE';
        var exp = c.expirationDate ? Math.round(c.expirationDate) : 0;
        lines.push(d + '\t' + flag + '\t' + p + '\t' + s + '\t' + exp + '\t' + c.name + '\t' + c.value);
      }
      sendResponse({success: true, netscape: lines.join('\n'), count: cookies.length});
    });
    return true;
  }
});
